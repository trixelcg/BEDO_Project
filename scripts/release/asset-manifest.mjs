/**
 * Generate the content-addressed runtime-asset manifest.
 *
 * ## Why this exists
 *
 * Cloud Run splits traffic per HTTP request, not per session. A page load is ~57
 * requests, and each one is routed independently, so during a canary the HTML can come
 * from revision A while a later asset request lands on revision B.
 *
 * For Vite's `/assets/index-<hash>.js` that shows up as a 404 (PERF-05/05B). For a
 * STABLE-name runtime asset it is worse and silent: `/Bedo_baked_v2.glb` exists on both
 * revisions, so the request succeeds — with the other generation's bytes. A bundle built
 * against the A1 model would happily render the frozen v2 model, or vice versa, with no
 * error anywhere.
 *
 * The fix is to give every versioned runtime asset a URL that contains its own content
 * hash. Two generations then occupy two different URLs, both present in the shared
 * bucket at once, so whichever revision answers the request returns the right bytes.
 *
 * ## Outputs (one source of truth, two consumers)
 *
 *   src/generated/assetManifest.ts   - imported by the app bundle
 *   public/runtime-manifest.json     - copied into dist/ by Vite, read by server.ts
 *
 * Both are generated; never hand-edit them.
 */
import { createHash } from 'crypto';
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'fs';
import path from 'path';

const ROOT = path.resolve(import.meta.dirname, '../..');
const PUBLIC = path.join(ROOT, 'public');

/**
 * Which runtime assets are content-addressed.
 *
 * These are the assets the 3D runtime fetches by URL and whose bytes may legitimately
 * differ between releases. Assets that are pure media and identical across generations
 * (the video, the answer-sheet PDFs, the favicon) keep stable names — a mismatch there is
 * harmless — but they are still uploaded to the shared bucket so they can never 404
 * across revisions.
 */
const VERSIONED_FILES = [
  'Bedo_baked_v2.glb',
  'rosendal_plains_2_4k.webp',
  ...readdirSync(path.join(PUBLIC, 'WaterShapes')).filter((f) => f.endsWith('.glb')).sort()
    .map((f) => `WaterShapes/${f}`),
];

/** Directories whose files must resolve as a consistent set (see basis note below). */
const VERSIONED_DIRS = ['basis'];

const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');
const short = (hex) => hex.slice(0, 12);

const manifest = {};
const uploads = [];

for (const rel of VERSIONED_FILES) {
  const abs = path.join(PUBLIC, rel);
  if (!existsSync(abs)) throw new Error(`versioned asset missing from public/: ${rel}`);
  const bytes = readFileSync(abs);
  const hash = sha256(bytes);
  const key = `runtime/${short(hash)}/${path.basename(rel)}`;
  manifest[rel] = key;
  uploads.push({ key, source: path.relative(ROOT, abs), sha256: hash, bytes: bytes.length });
}

/**
 * The Basis transcoder is a COUPLED pair: KTX2Loader.setTranscoderPath() takes a
 * directory and then fetches `basis_transcoder.js` and `.wasm` from it. A mismatched
 * pair is a hard failure, so the directory is versioned as a unit by the combined hash
 * of its sorted contents rather than per file.
 */
for (const dir of VERSIONED_DIRS) {
  const absDir = path.join(PUBLIC, dir);
  if (!existsSync(absDir)) continue;
  const files = readdirSync(absDir).filter((f) => !f.startsWith('.')).sort();
  const combined = createHash('sha256');
  const members = [];
  for (const f of files) {
    const bytes = readFileSync(path.join(absDir, f));
    combined.update(f).update(sha256(bytes));
    members.push({ name: f, bytes, sha256: sha256(bytes) });
  }
  const hash = combined.digest('hex');
  const prefix = `runtime/${dir}-${short(hash)}`;
  manifest[`${dir}/`] = `${prefix}/`;
  for (const m of members) {
    uploads.push({ key: `${prefix}/${m.name}`, source: path.relative(ROOT, path.join(absDir, m.name)),
      sha256: m.sha256, bytes: m.bytes.length });
  }
}

const banner = `// GENERATED by scripts/release/asset-manifest.mjs — do not edit.\n` +
  `// Maps a logical runtime asset name to its content-addressed path.\n`;

writeFileSync(path.join(ROOT, 'src/generated/assetManifest.ts'),
  `${banner}export const RUNTIME_ASSET_MANIFEST: Record<string, string> = ${JSON.stringify(manifest, null, 2)};\n`);

writeFileSync(path.join(ROOT, 'public/runtime-manifest.json'),
  JSON.stringify({ manifest, uploads }, null, 2) + '\n');

if (process.argv.includes('--print')) {
  for (const [k, v] of Object.entries(manifest)) console.log(`  ${k.padEnd(42)} -> ${v}`);
  console.log(`  ${uploads.length} objects to publish`);
}
